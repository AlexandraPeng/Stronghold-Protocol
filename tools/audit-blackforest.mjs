// Offline source inventory for the custom mode. This does not enable a relic:
// each combat/recruitment adapter still needs an authored implementation/test.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const source = new URL('.cache/gamedata/excel/roguelike_topic_table.json', root);
const raw = await readFile(source, 'utf8');
const table = JSON.parse(raw).details.rogue_6;
const unavailable = new Set(['zone_into_node_attach_buff', 'immediate_reward_on_vehicle_broken',
  'vehicle_move_no_ap_cost', 'scrap_fill_up', 'layer_meet_node_types', 'unlock_node',
  'immediate_reward_on_collection_complete', 'map_gen_delta', 'recruit_extra_prob']);
const catalog = Object.values(table.items).filter(i => i.type === 'RELIC' && table.relics[i.id]
  && !/_[abc]$/.test(i.id)).map(i => {
  const buffs = table.relics[i.id].buffs.map(b => ({ key: b.key,
    params: Object.fromEntries(b.blackboard.map(p => [p.key, p.valueStr ?? p.value])) }));
  return { id: i.id, name: i.name, rarity: i.rarity, baseUsage: i.usage,
    source: `https://prts.wiki/w/${encodeURIComponent(i.name)}`,
    buffs, needsAdapter: [...new Set(buffs.map(b => b.key))],
    unavailableSubsystems: [...new Set(buffs.map(b => b.key).filter(k => unavailable.has(k)))],
    status: 'pending-review' };
});
const out = new URL('.cache/blackforest-audit/', root);
await mkdir(out, { recursive: true });
const inventory = {
  sourceSha256: createHash('sha256').update(raw).digest('hex'),
  source: 'https://raw.githubusercontent.com/Kengxxiao/ArknightsGameData/master/zh_CN/gamedata/excel/roguelike_topic_table.json',
  wiki: 'https://prts.wiki/w/沉沦者的黑流树海/拟造物质编目',
  structure: 'structured-base', catalog,
};
await writeFile(new URL('catalog.json', out), JSON.stringify(inventory, null, 2));
if (process.argv.includes('--write-source')) {
  const {catalog: rows, ...meta} = inventory;
  const ignore = ' // i18n-ignore: sourced custom content data';
  await writeFile(new URL('shared/blackforestSource.js', root),
    '// Structured base values from PRTS and official rogue_6 table. Generated by tools/audit-blackforest.mjs.\n' +
    `export const BLACKFOREST_SOURCE = ${JSON.stringify(meta)};${ignore}\n` +
    'export const BLACKFOREST_CATALOG = [\n' +
    rows.map(r => `  ${JSON.stringify(r)},${ignore}`).join('\n') + '\n];\n');
}
const { RELICS } = await import('../shared/blackforestRelics.js');
const enabled = new Set(RELICS.map(r=>r.id));
const status = catalog.map(r=>({id:r.id,name:r.name,status:enabled.has(r.id)?'enabled':r.unavailableSubsystems.length?'no-equivalent-subsystem':'pending-adapter',keys:r.needsAdapter}));
await writeFile(new URL('coverage.json', out), JSON.stringify(status,null,2));
console.log(`Inventoried ${catalog.length} base relics; no advanced structure variants enabled.`);
