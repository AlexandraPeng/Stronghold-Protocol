// Usage: node tools/apply-unite-tuning.mjs exported.json [--write]
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { validateUniteTuning } from '../shared/uniteTuningSchema.js';
const root = new URL('../', import.meta.url);
const read = async rel => JSON.parse(await fs.readFile(new URL(rel,root),'utf8'));
if (!process.argv[2]) throw new Error('Usage: node tools/apply-unite-tuning.mjs exported.json [--write]');
const input = await fs.readFile(process.argv[2],'utf8');
if (Buffer.byteLength(input)>1024*1024) throw new Error('Maximum configuration size: 1 MiB');
const value = validateUniteTuning(JSON.parse(input),await read('data/enemies.json'),await read('data/waves.json'),await read('data/choices.json'),await read('data/stages.json'));
if (process.argv.includes('--write')) {
  const target = new URL('shared/uniteTuning.js',root);
  const backup = new URL(`shared/uniteTuning.js.${Date.now()}.bak`,root);
  await fs.copyFile(target,backup);
  const temporary = new URL('shared/uniteTuning.js.tmp',root);
  await fs.writeFile(temporary,'// Custom balance only; generated by tools/apply-unite-tuning.mjs. Official tables remain untouched.\nexport const UNITE_TUNING = '+JSON.stringify(value,null,2)+';\n');
  await fs.rename(temporary,target);
  console.log(`Applied: ${fileURLToPath(target)}\nBackup: ${fileURLToPath(backup)}\nRestart the local server and refresh clients to use this configuration.`);
} else console.log('Valid configuration. Add --write to apply locally; no files changed.');
