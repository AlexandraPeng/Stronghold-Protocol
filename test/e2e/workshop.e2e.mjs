// CHROME_PATH=/path/to/chrome node --test test/e2e/workshop.e2e.mjs
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { CHROME, ROOT, hasChrome, startRealServer } from './client.mjs';

test('workshop: actual battle, local save/reload, file export/import and malformed-file rejection', {skip:!hasChrome(), timeout:60000}, async () => {
  const server=await startRealServer(),dir=path.join(ROOT,'.cache','workshop-e2e');
  await fs.mkdir(dir,{recursive:true});
  // The optional module URL lets environments with a bundled Playwright run this same UI flow.
  const automation = process.env.WORKSHOP_PLAYWRIGHT_MODULE ? (await import(process.env.WORKSHOP_PLAYWRIGHT_MODULE)).chromium : (await import('puppeteer-core')).default;
  const browser=await automation.launch({executablePath:CHROME,headless:true,args:['--no-sandbox']});
  try {
    const p=await browser.newPage(),errors=[],connections=[];
    p.on('pageerror',e=>errors.push(e.message));p.on('request',r=>{if(r.url().includes('/ws'))connections.push(r.url());});
    const viewport = size => p.setViewport ? p.setViewport(size) : p.setViewportSize(size);
    await viewport({width:1440,height:1000});
    await p.goto(`${server.base}/workshop/index.html`);
    await p.waitForFunction(()=>!!window.__workshop);
    let discard = false;
    p.on('dialog',d=>discard?d.accept():d.dismiss());
    assert.equal(await p.evaluate(()=>document.getElementById('pause').disabled),true);
    const firstEnemy=await p.evaluate(()=>document.getElementById('enemyPick').value);
    await p.click('#enemyNext');
    assert.notEqual(await p.evaluate(()=>document.getElementById('enemyPick').value),firstEnemy);
    await p.click('#enemyPrev');
    assert.equal(await p.evaluate(()=>document.getElementById('enemyPick').value),firstEnemy);
    await p.click('#addAlly');await p.type('#enemySearch','enemy_1000_gopro_2');await p.click('#addEnemy');
    await p.click('#new');
    assert.equal(await p.evaluate(()=>window.__workshop.doc.allies.length),1,'cancel replacing unsaved work');
    await p.click('#waves > .card .card-head button');
    assert.equal(await p.evaluate(()=>window.__workshop.doc.waves.length),2);
    assert.equal(await p.evaluate(()=>document.getElementById('enemyCount').textContent),'10 / 300');
    await p.evaluate(()=>{const inputs=document.querySelectorAll('#waves > .card');const time=inputs[0].querySelectorAll('.row input')[1];time.value='8';time.dispatchEvent(new Event('change',{bubbles:true}));});
    await p.click('#sortWaves');
    assert.deepEqual(await p.evaluate(()=>window.__workshop.doc.waves.map(w=>w.time)),[0,8]);
    await p.click('#waves > .card:last-child .card-head button:last-child');
    assert.equal(await p.evaluate(()=>document.querySelectorAll('.timeline-row').length),1);
    await p.click('#allies details:nth-of-type(3) summary');await p.click('#allies details:nth-of-type(3) > button');
    assert.equal(await p.evaluate(()=>window.__workshop.doc.allies[0].rules.length),1);
    await p.click('#addAlliance');
    await p.click('#allies details:nth-of-type(4) summary');await p.click('#allies details:nth-of-type(4) input');
    await p.click('#waves details:nth-of-type(5) summary');await p.click('#waves details:nth-of-type(5) input');
    assert.equal(await p.evaluate(()=>window.__workshop.doc.waves[0].alliances.length),1);
    await p.click('#run');await p.waitForFunction(()=>window.__workshop.battle?.time>=2);
    assert.equal(await p.evaluate(()=>window.__workshop.battle.errorCount),0);
    assert.equal(await p.evaluate(()=>window.__workshop.battle.total),5);
    await p.click('#pause');
    await p.type('#name',' · 编辑');
    assert.match(await p.evaluate(()=>document.getElementById('battleState').textContent),/配置已修改/);
    await p.click('#stop');
    assert.equal(await p.evaluate(()=>window.__workshop.battle),null);
    assert.equal(await p.evaluate(()=>document.getElementById('pause').disabled),true);
    await p.click('#save');await p.reload();await p.waitForFunction(()=>!!window.__workshop);await p.click('#load');
    assert.equal(await p.evaluate(()=>window.__workshop.doc.allies.length),1);
    assert.equal(await p.evaluate(()=>window.__workshop.doc.waves.length),1);
    // Capture the Blob generated by the actual export button, then import it with a real file input.
    await p.evaluate(()=>{const make=URL.createObjectURL.bind(URL);URL.createObjectURL=blob=>{window.__exportedBlob=blob;return make(blob);};});
    await p.click('#export');const text=await p.evaluate(()=>window.__exportedBlob.text());
    const exported=path.join(dir,'roundtrip.json');await fs.writeFile(exported,text);
    await p.click('#new');assert.equal(await p.evaluate(()=>window.__workshop.doc.allies.length),0);
    const file=await p.$('#import'),upload=path=>file.uploadFile?file.uploadFile(path):file.setInputFiles(path);await upload(exported);
    await p.waitForFunction(()=>document.getElementById('status').textContent.includes('已导入'));
    assert.deepEqual(await p.evaluate(()=>JSON.parse(JSON.stringify(window.__workshop.doc))),JSON.parse(text));
    const invalid=path.join(dir,'invalid.json');await fs.writeFile(invalid,'{"version":1,"__proto__":{"polluted":true}}');
    await upload(invalid);await p.waitForFunction(()=>document.getElementById('status').classList.contains('error'));
    assert.equal(await p.evaluate(()=>window.__workshop.doc.allies.length),1,'bad import preserves the previous work');
    assert.equal(await p.evaluate(()=>({}).polluted),undefined);
    discard=true;
    await p.screenshot({path:path.join(dir,'desktop.png'),fullPage:true});
    await viewport({width:390,height:844});await p.screenshot({path:path.join(dir,'mobile.png'),fullPage:true});
    assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile has no horizontal overflow');
    assert.deepEqual(errors,[]);assert.deepEqual(connections,[],'workshop never connects to multiplayer');
  } finally {await browser.close();await server.stop({hard:true});}
});
